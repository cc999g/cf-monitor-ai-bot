// ---------- 取文案 ----------
export function t(lang, key, vars) {
  const dict = M[lang] || M[DEFAULT_LANG];
  let s = dict[key] ?? M[DEFAULT_LANG][key] ?? key;
  if (vars) {
    for (const k in vars) {
      s = s.split('{' + k + '}').join(String(vars[k]));
    }
  }
  return s;
}

// ---------- 判断文字是否为某按钮（匹配全部语言，兼容旧键盘） ----------
export function isBtn(text, key) {
  if (typeof text !== 'string') return false;
  for (const l of LANGS) {
    if (M[l][key] === text) return true;
  }
  return false;
}

